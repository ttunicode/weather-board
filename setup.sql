create table if not exists public.wx_tasks (
  id bigint generated by default as identity primary key,
  title text not null constraint wx_tasks_title_not_blank check (length(trim(title)) > 0),
  region text not null constraint wx_tasks_region_allowed check (region in ('세종', '대전', '태안', '보령')),
  kind text not null constraint wx_tasks_kind_allowed check (kind in ('야외', '고소', '실내')),
  owner text not null constraint wx_tasks_owner_not_blank check (length(trim(owner)) > 0),
  created_at timestamptz not null default now()
);

alter table public.wx_tasks enable row level security;

grant select, insert on table public.wx_tasks to anon;
grant usage, select on sequence public.wx_tasks_id_seq to anon;

drop policy if exists wx_tasks_public_read on public.wx_tasks;
create policy wx_tasks_public_read
  on public.wx_tasks for select to anon
  using (true);

drop policy if exists wx_tasks_public_insert on public.wx_tasks;
create policy wx_tasks_public_insert
  on public.wx_tasks for insert to anon
  with check (true);

insert into public.wx_tasks (title, region, kind, owner)
select seed.title, seed.region, seed.kind, seed.owner
from (values
  ('다중이용시설 안전점검', '세종', '야외', '김안전'),
  ('시민 안전체험 행사 운영', '보령', '야외', '이행사'),
  ('옥상 태양광 설비 점검', '태안', '고소', '박설비'),
  ('하천 수위계 확인', '대전', '야외', '최현장'),
  ('청사 외벽 간판 보수', '세종', '고소', '정시설'),
  ('비상연락 훈련', '대전', '실내', '한상황')
) as seed(title, region, kind, owner)
where not exists (
  select 1
  from public.wx_tasks as existing
  where existing.title = seed.title
    and existing.region = seed.region
    and existing.kind = seed.kind
    and existing.owner = seed.owner
);
